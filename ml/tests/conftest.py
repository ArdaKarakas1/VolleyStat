"""Synthetic clips for the tests. No real match footage is used anywhere.

Every clip is generated by ffmpeg from lavfi sources. The clips prove that the
plumbing works on a signal with known boundaries; they say nothing about real video.
"""
import os
import shutil
import subprocess
from types import SimpleNamespace

import pytest

# Active stretches of the two "rally" clips, in milliseconds.
RALLIES_MS = [(4000, 10000), (16000, 24000), (30000, 36000)]
RALLY_CLIP_MS = 40000
SIZE, RATE = "320x180", 15
ENCODE = ["-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p"]


def _ffmpeg(*arguments):
    subprocess.run(["ffmpeg", "-v", "error", "-y", *map(str, arguments)], check=True)


def _lavfi(source, seconds):
    return ["-f", "lavfi", "-t", seconds, "-i", f"{source}=size={SIZE}:rate={RATE}"]


@pytest.fixture(scope="session")
def clips(tmp_path_factory):
    if not (shutil.which("ffmpeg") and shutil.which("ffprobe")):
        if os.environ.get("VOLLEYSTAT_REQUIRE_FFMPEG"):
            pytest.fail("ffmpeg/ffprobe are required but not installed")
        pytest.skip("ffmpeg/ffprobe not installed")
    folder = tmp_path_factory.mktemp("clips")
    seconds = RALLY_CLIP_MS // 1000
    active = "+".join(f"between(t,{start / 1000},{end / 1000})" for start, end in RALLIES_MS)

    # One background for the whole clip with sensor-like noise all the time. A white box
    # rests in the idle stretches and travels in the active ones, so idle time is not
    # pixel-identical and there is no scene cut at the boundaries.
    moving_box = folder / "moving_box.mp4"
    _ffmpeg(
        "-f", "lavfi", "-i", f"color=c=0x3a6ea5:s={SIZE}:r={RATE}:d={seconds}",
        "-f", "lavfi", "-i", f"color=c=white:s=28x28:r={RATE}:d={seconds}",
        "-filter_complex",
        "[0]noise=alls=6:allf=t[bg];"
        f"[bg][1]overlay=x='if({active},146+110*sin(2*PI*t*0.9),146)':y='if({active},76+60*cos(2*PI*t*0.6),76)'",
        *ENCODE, moving_box,
    )

    # Idle stretches from a still source, active stretches from a moving source, joined
    # at the same boundaries. Every joint is a scene cut.
    inputs, position = [], 0
    for start, end in [*RALLIES_MS, (RALLY_CLIP_MS, RALLY_CLIP_MS)]:
        if start > position:
            inputs += _lavfi("smptebars", (start - position) / 1000)
        if end > start:
            inputs += _lavfi("testsrc2", (end - start) / 1000)
        position = end
    concatenated = folder / "concatenated.mp4"
    _ffmpeg(*inputs, "-filter_complex", f"concat=n={inputs.count('-i')}:v=1:a=0", *ENCODE, concatenated)

    still = folder / "still.mp4"
    _ffmpeg(*_lavfi("smptebars", 20), *ENCODE, still)
    still_noisy = folder / "still_noisy.mp4"
    _ffmpeg("-f", "lavfi", "-i", f"color=c=0x3a6ea5:s={SIZE}:r={RATE}:d=20", "-vf", "noise=alls=6:allf=t", *ENCODE, still_noisy)
    busy = folder / "busy.mp4"
    _ffmpeg(*_lavfi("testsrc2", 20), *ENCODE, busy)

    # The container lasts 9 s (audio) but the picture ends after 6 s.
    short_picture = folder / "short_picture.mp4"
    _ffmpeg(*_lavfi("testsrc2", 6), "-f", "lavfi", "-t", 9, "-i", "sine=frequency=440", *ENCODE, "-c:a", "aac", short_picture)
    webm = folder / "busy.webm"
    _ffmpeg(*_lavfi("testsrc2", 6), "-c:v", "libvpx-vp9", "-b:v", "200k", webm)

    not_a_video = folder / "not_a_video.mp4"
    not_a_video.write_bytes(b"this is not a video" * 64)
    return SimpleNamespace(
        moving_box=moving_box, concatenated=concatenated, still=still, still_noisy=still_noisy,
        busy=busy, short_picture=short_picture, webm=webm, not_a_video=not_a_video,
        rallies_ms=list(RALLIES_MS), rally_clip_ms=RALLY_CLIP_MS,
    )
